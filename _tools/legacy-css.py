#!/usr/bin/env python3
"""Regenerate css/legacy.css: the Tachyons utility classes that old content still uses.

Old posts, wiki pages and library items contain inline class="..." markup written for Tachyons.
The redesigned templates do not use Tachyons, so instead of loading all of it we keep only the
rules for classes that appear in content, scoped to .post-body. Run from the repo root:

    python3 _tools/legacy-css.py
"""
import glob, re

PATTERNS = ('_posts/*', 'wiki/**/*.md', 'wiki/**/*.html', '_library/*', 'blogchains/*', '*.md',
            '_includes/blogchain-nav-*.html', '_includes/tufte-*.html')
used = set()
for pattern in PATTERNS:
    for path in glob.glob(pattern, recursive=True):
        try:
            text = open(path, errors='ignore').read()
        except IsADirectoryError:
            continue
        for m in re.finditer(r'class="([^"]+)"', text):
            used.update(m.group(1).split())

css = re.sub(r'/\*.*?\*/', '', open('css/tachyons.min.css').read(), flags=re.S)

def pick(block):
    out = []
    for m in re.finditer(r'([^{}]+)\{([^{}]*)\}', block):
        selectors = [s.strip() for s in m.group(1).split(',')]
        keep = [s for s in selectors
                if re.fullmatch(r'\.([A-Za-z0-9_-]+)(:[a-z-]+)*', s) and re.match(r'\.([A-Za-z0-9_-]+)', s).group(1) in used]
        if keep:
            out.append('.post-body ' + ', .post-body '.join(keep) + '{' + m.group(2) + '}')
    return out

rules, pos = [], 0
for m in re.finditer(r'@media([^{]+)\{((?:[^{}]+\{[^{}]*\})+)\s*\}', css):
    rules += pick(css[pos:m.start()])
    inner = pick(m.group(2))
    if inner:
        rules.append('@media' + m.group(1).rstrip() + '{' + ''.join(inner) + '}')
    pos = m.end()
rules += pick(css[pos:])

custom = '''.post-body .newgreen{color:var(--green-ink)}
.post-body .b--newgreen{border-color:var(--mark)}
.post-body .bg-newgreen-light{background:var(--wash)}
.post-body .ibmplexmono{font-family:var(--font-mono)}
'''
header = ('/* Generated by _tools/legacy-css.py from tachyons.min.css: only the utility classes that old post,\n'
          '   wiki and library content uses, scoped to .post-body so they cannot leak into the new templates. */\n')
open('css/legacy.css', 'w').write(header + '\n'.join(rules) + '\n' + custom)
print(f'{len(used)} classes found in content; {len(rules)} rules kept; {len(open("css/legacy.css").read())} bytes')
